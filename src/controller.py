"""Task-agnostic bounded verification / repair / resumption state machine.

Task semantics and recovery language are generated by an injected planner.
Only measured predicates verify a contract. The runner owns all model queries
and env.step; a handoff is recorded only after its nominal action executes.
"""
from collections import deque
from copy import deepcopy
from dataclasses import dataclass
import math

from .planning.schema import PlanningError, RecoveryPlan
from .verification.physical_verifier import PhysicalVerifier


@dataclass(frozen=True)
class Limits:
    actions: int = 520
    queries: int = 520
    local_repair: int = 32
    total_repair: int = 160
    rechecks: int = 3
    cooldown: int = 8
    stagnation: int = 180

    def __post_init__(self):
        if any(type(v) is not int or v < 1 for v in vars(self).values()):
            raise ValueError('Runtime limits must be positive integers')


class Controller:
    VERSION = 'generated_task_measured_repair_h1_v1'

    def __init__(self, task, planner, capabilities, *, limits=None, mode='framework', verifier=None):
        if mode not in ('framework', 'baseline'):
            raise ValueError('Expected framework or baseline')
        self.task, self.planner, self.capabilities = task, planner, frozenset(capabilities)
        self.limits, self.mode = limits or Limits(), mode
        self.verifier = verifier or PhysicalVerifier()
        self.actions = self.queries = self.repair_actions = 0
        self.history = deque(maxlen=max(self.limits.stagnation + 1, self.limits.rechecks, 3))
        self.active = self.pending = self.handoff_pending = None
        self.repairs = []
        self._streaks, self._lost_streaks, self._achieved = {}, {}, set()
        self._cooldown_until = 0
        self._last_progress = 0
        self._last_attempt = None
        self._force_repair = False
        self.complete = False

    @property
    def predicates(self):
        predicates = [*self.task.goals, *self.task.milestones]
        if self.active:
            plan = self.active['plan']
            predicates += [*plan.preserve, *(p for group in plan.alternatives for p in group)]
        return tuple(dict.fromkeys(predicates))

    @property
    def budget(self):
        return dict(actions=self.actions, queries=self.queries, repair_actions=self.repair_actions,
                    remaining_actions=self.limits.actions-self.actions,
                    remaining_queries=self.limits.queries-self.queries,
                    remaining_repair=self.limits.total_repair-self.repair_actions)

    @property
    def summary(self):
        records = deepcopy(self.repairs)
        for r in records:
            r['plan'] = r['plan'].to_dict()
        return dict(version=self.VERSION, mode=self.mode, task=self.task.to_dict(),
                    budget=self.budget, complete=self.complete, repairs=records)

    def charge_queries(self, count=1):
        """Count attempted queries, including rejected nominal proposals."""
        if type(count) is not int or count < 1 or self.queries + count > self.limits.queries:
            raise RuntimeError('query_budget_exhausted')
        self.queries += count

    def _values(self, observation):
        return {p: self.verifier.evaluate(p, observation, self.history)
                for p in dict.fromkeys((*self.task.goals, *self.task.milestones))}

    def _remember(self, observation):
        self.history.append(deepcopy(observation))
        values = self._values(observation)
        for p, value in values.items():
            self._streaks[p] = self._streaks.get(p, 0)+1 if value is True and observation.index > 0 else 0
            self._lost_streaks[p] = self._lost_streaks.get(p, 0)+1 if value is False else 0
            if self._streaks[p] >= self.limits.rechecks and p not in self._achieved:
                self._achieved.add(p)
                self._last_progress = observation.index
        self.complete = self.verifier.check_all(self.task.goals, observation, self.history) is True

    def _event(self, observation):
        lost = [p.to_dict() for p in self._achieved
                if self._lost_streaks.get(p, 0) >= self.limits.rechecks]
        if lost:
            return dict(reason='durable_progress_lost', predicates=sorted(lost, key=str))
        if observation.index-self._last_progress >= self.limits.stagnation:
            return dict(reason='no_verified_progress', since=self._last_progress)
        return None

    def _context(self, observation):
        # Cooldown alone does not permit retrying the identical failed context.
        return dict(facts=deepcopy(observation.facts), positions=deepcopy(observation.positions))

    def _changed(self, observation):
        if self._last_attempt is None:
            return True
        recent = list(self.history)[-self.limits.rechecks:]
        if len(recent) < self.limits.rechecks or recent[0].index <= self._last_attempt['index']:
            return False
        old = self._last_attempt['context']
        for key, value in observation.facts.items():
            if value is not None and old['facts'].get(key) is not None and value != old['facts'][key]:
                if all(o.facts.get(key) == value for o in recent):
                    return True
        return any(all(key in o.positions and math.dist(pos, o.positions[key]) >= .020 for o in recent)
                   for key, pos in old['positions'].items())

    def before(self, observation):
        if self.pending is not None or observation.index != self.actions:
            raise ValueError('Expected sequential before/after pairs')
        if self.actions >= self.limits.actions or self.queries >= self.limits.queries:
            raise RuntimeError('episode_budget_exhausted')
        if not self.history:
            self._remember(observation)
        elif observation.fingerprint != self.history[-1].fingerprint:
            raise ValueError('Current endpoint changed without execution')
        if self.complete:
            raise RuntimeError('task_complete_no_further_action')
        event, blocked = self._event(observation), None
        if (self.mode == 'framework' and self.active is None and self.handoff_pending is None
                and event and self.actions >= self._cooldown_until
                and self.repair_actions < self.limits.total_repair and self._changed(observation)):
            self._last_attempt = dict(index=observation.index, context=self._context(observation))
            self._cooldown_until = self.actions + self.limits.cooldown
            try:
                plan = self.planner.recover(self.task, deepcopy(observation), self.capabilities,
                    event, [dict(index=o.index, facts=o.facts, positions=o.positions)
                            for o in list(self.history)[-6:]])
                if plan is None:
                    blocked = 'planner_deferred'
                else:
                    plan = RecoveryPlan.parse(plan.to_dict(), {e.id for e in observation.entities},
                                              self.capabilities)
                    # The environment may need to measure new generated clauses.
                    # Runtime refreshes this SAME endpoint before any action.
                    repair = dict(id=len(self.repairs)+1, entry=self.actions, plan=plan,
                                  used=0, streaks=[0]*len(plan.alternatives), ready=False,
                                  preserve_lost=False, verified=False, exit_reason=None,
                                  handoff_step=None, handoff_assessment=None,
                                  post_handoff_loss_step=None, completed_after_handoff=False)
                    self.repairs.append(repair)
                    self.active = repair
            except PlanningError as error:
                blocked = 'planning_unavailable: ' + str(error)
        active = self.active
        handoff = active is not None and active['ready'] and not self._force_repair
        owner = 'nominal' if active is None or handoff else 'repair'
        self._force_repair = False
        decision = dict(step=self.actions, owner=owner, handoff=handoff,
                        language=active['plan'].instruction if owner == 'repair' else self.task.instruction,
                        repair_id=active['id'] if active else None,
                        trigger=event, blocked=blocked, budget=self.budget)
        self.pending = deepcopy(decision)
        return decision

    def refresh(self, observation):
        """Add freshly measured generated predicates at the unchanged endpoint."""
        previous = self.history[-1]
        old, new = previous.to_dict(), observation.to_dict()
        for key in old:
            if key != 'facts' and old[key] != new[key]:
                raise ValueError('Predicate refresh changed the physical endpoint')
        if any(observation.facts.get(k) != v for k, v in previous.facts.items()):
            raise ValueError('Predicate refresh changed an existing measurement')
        self.history[-1] = deepcopy(observation)
        if self.active and self.active['used'] == 0:
            plan = self.active['plan']
            # Preservation is never invented from the model's claim of truth.
            if self.verifier.check_all(plan.preserve, observation, self.history) is not True:
                self.active['exit_reason'] = 'unverifiable_entry_preservation'
                self.active = None
                self.pending = None
                return False
            if any(self.verifier.check_all(group, observation, self.history) is True
                   for group in plan.alternatives):
                self.active['exit_reason'] = 'already_satisfied_contract'
                self.active = None
                self.pending = None
                return False
        return True

    def reject_handoff(self, decision, assessment):
        if self.pending != decision or not decision['handoff']:
            raise ValueError('No pending handoff proposal')
        self.active['handoff_assessment'] = deepcopy(assessment)
        self.pending = None
        self._force_repair = True

    def after(self, observation, action, decision, *, handoff_assessment=None):
        if (self.pending != decision or observation.index != self.actions+1
                or self.queries < self.actions+1
                or len(action) != 7 or not all(math.isfinite(float(v)) for v in action)):
            raise ValueError('Expected unchanged pending decision and fresh executed H1 endpoint')
        if decision['handoff'] and (not isinstance(handoff_assessment, dict)
                                    or handoff_assessment.get('accept') is not True):
            raise ValueError('A handoff needs an accepted assessment of its nominal proposal')
        self.actions += 1
        self._remember(observation)
        events = []
        if decision['owner'] == 'repair':
            repair = self.active
            repair['used'] += 1
            self.repair_actions += 1
            # Only post-entry endpoints count towards the local contract.
            history = [o for o in self.history if o.index > repair['entry']]
            preserved = self.verifier.check_all(repair['plan'].preserve, observation, history)
            if preserved is not True:
                repair['preserve_lost'] = True
            checks = [self.verifier.check_all(group, observation, history)
                      for group in repair['plan'].alternatives]
            repair['streaks'] = [n+1 if passed is True and not repair['preserve_lost'] else 0
                                 for n, passed in zip(repair['streaks'], checks)]
            repair['ready'] = any(n >= self.limits.rechecks for n in repair['streaks'])
            reason = None
            if self.complete:
                reason = 'task_completion_during_repair'
            elif repair['used'] >= self.limits.local_repair:
                reason = 'local_budget_exit_unverified'
            elif self.repair_actions >= self.limits.total_repair:
                reason = 'total_repair_budget_exit_unverified'
            elif self.actions >= self.limits.actions or self.queries >= self.limits.queries:
                reason = 'episode_budget_exit_unverified'
            if reason:
                repair['exit_reason'] = reason
                self.active = None
                self.handoff_pending = repair['id'] if not self.complete else None
                self._last_attempt = dict(index=observation.index, context=self._context(observation))
                self._cooldown_until = self.actions + self.limits.cooldown
                events.append(dict(type='repair_exit', reason=reason, verified=False))
            elif repair['ready']:
                events.append(dict(type='local_recovery_verified', repair_id=repair['id']))
        elif decision['handoff']:
            repair = self.active
            repair.update(verified=True, exit_reason='verified_handoff', handoff_step=self.actions-1,
                          handoff_assessment=deepcopy(handoff_assessment))
            self.active = None
            self._cooldown_until = self.actions + self.limits.cooldown
            self._last_attempt = dict(index=observation.index, context=self._context(observation))
            events.append(dict(type='handoff_executed', repair_id=repair['id'], verified=True))
        elif self.handoff_pending is not None:
            repair = self.repairs[self.handoff_pending-1]
            repair['handoff_step'] = self.actions-1
            events.append(dict(type='handoff_executed', repair_id=repair['id'], verified=False))
            self.handoff_pending = None
        for repair in self.repairs:
            if repair['handoff_step'] is None:
                continue
            checks = [self.verifier.check_all(group, observation, self.history)
                      for group in repair['plan'].alternatives]
            repair['post_handoff_acceptance'] = checks
            if (all(value is False for value in checks) and repair['post_handoff_loss_step'] is None
                    and not self.complete):
                repair['post_handoff_loss_step'] = self.actions-1
                events.append(dict(type='post_handoff_contract_lost', repair_id=repair['id']))
            if self.complete:
                repair['completed_after_handoff'] = True
        if self.complete:
            events.append(dict(type='task_complete'))
        self.pending = None
        return dict(events=events, budget=self.budget, complete=self.complete,
                    native_success=observation.native_success)

    def finish(self, termination):
        """Close a bounded run without inventing an executed handoff."""
        if self.active is not None:
            self.active['exit_reason'] = termination + '_exit_unverified'
            self.active = None
        self.pending = None
